import smtplib
from email.mime.multipart import MIMEMultipart
from email.mime.text import MIMEText
from openai import OpenAI
import os
from dotenv import load_dotenv


# 1. Load environment variables FIRST before calling getenv
load_dotenv()

# Set OpenAI API key (will fetch from .env or your environment)
api_key = os.getenv("OPENAI_API_KEY")
app_password = os.getenv("APP_PASSWORD")

os.environ["APP_PASSWORD"] = app_password
os.environ["OPENAI_API_KEY"] = api_key

# 1. Configure your API Key and Email details
OPENAI_API_KEY = api_key
SENDER_EMAIL = "titu.durais@gmail.com"
APP_PASSWORD = app_password
RECEIVER_EMAIL = "peacemakert2@gmail.com"

# 2. Initialize the OpenAI client
client = OpenAI(api_key=OPENAI_API_KEY)


def generate_ai_content():
  print("Asking AI to write the email...")
  response = client.chat.completions.create(
      model="gpt-4o-mini",
      messages=[{
          "role":
              "user",
          "content": (
              "Write a short, friendly daily status update email. Include"
              " a motivational quote and a summary of why AI automation"
              " is awesome. Keep it concise."
          ),
      }],
  )
  return response.choices[0].message.content


def send_email(email_body):
  print("Connecting to Gmail and sending...")
  msg = MIMEMultipart()
  msg["From"] = SENDER_EMAIL
  msg["To"] = RECEIVER_EMAIL
  msg["Subject"] = "🤖 Your Automated AI Daily Update"

  # Attach the text generated by OpenAI
  msg.attach(MIMEText(email_body, "plain"))

  # Connect to Gmail's secure SMTP server (Port 465)
  with smtplib.SMTP_SSL("smtp.gmail.com", 465) as server:
    server.login(SENDER_EMAIL, APP_PASSWORD)
    server.sendmail(SENDER_EMAIL, RECEIVER_EMAIL, msg.as_string())

  print("Email sent successfully!")


if __name__ == "__main__":
  content = generate_ai_content()
  send_email(content)